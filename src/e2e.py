"""index.html を実ブラウザで動かして、画面の行き来と主要な操作を確かめる(Playwright)。"""
import sys, os
from playwright.sync_api import sync_playwright
HERE = os.path.dirname(os.path.abspath(__file__))
URL = 'file://' + os.path.abspath(os.path.join(HERE, '..', 'index.html'))
SHOT = sys.argv[1] if len(sys.argv) > 1 else None
fails = []
def ok(c, m):
    print(('ok  : ' if c else 'FAIL: ') + m)
    if not c: fails.append(m)

with sync_playwright() as p:
    b = p.chromium.launch(executable_path='/opt/pw-browsers/chromium')
    for name, w, h in (('desktop', 1100, 900), ('phone', 390, 800)):
        ctx = b.new_context(viewport={'width': w, 'height': h})
        pg = ctx.new_page()
        errs = []
        pg.on('pageerror', lambda e: errs.append(str(e)))
        pg.goto(URL)
        pg.wait_for_selector('.stairs')
        hs = lambda: pg.evaluate('location.hash')
        noscroll = lambda: pg.evaluate('document.documentElement.scrollWidth <= window.innerWidth')
        # 画面1: 授業
        ok(pg.locator('h1.ttl').inner_text() == 'レベル合わせるぞい', f'{name}: 最初は授業を選ぶ画面')
        ok(pg.locator('.spine').count() == 0 and pg.locator('.rec').count() == 0, f'{name}: 授業の画面に本棚やおすすめは出ない(1画面1用事)')
        ok(pg.locator('text=クイズ').count() == 0, f'{name}: 画面に「クイズ」がない')
        ok(noscroll(), f'{name}: 横スクロールなし(授業)')
        pg.click('[data-stage="2"]')
        ok(hs() in ('', '#home') and pg.locator('.stairs').count() == 1, f'{name}: 学年を選んでも勝手に画面は変わらない')
        ok(pg.locator('.step.on').count() == 1 and pg.locator('.step.done').count() == 2, f'{name}: 2年までを選ぶと階段が塗られる')
        pg.click('[data-act="toggle"]')
        ok(pg.locator('.course').count() == 33, f'{name}: 授業が33科目並ぶ')
        pg.click('[data-stage="1"]')
        first = pg.locator('.course').first
        before = first.get_attribute('aria-pressed'); first.click()
        ok(pg.locator('.course').first.get_attribute('aria-pressed') != before and pg.locator('.step.on').count() == 0, f'{name}: 授業を1つずつ切り替えられる')
        pg.click('[data-stage="1"]'); pg.click('[data-act="toggle"]')
        if SHOT: pg.screenshot(path=f'{SHOT}/{name}-1home.png')
        # 画面2: おすすめ
        pg.click('.go')
        pg.wait_for_selector('.rec')
        ok(hs() == '#recommend' and pg.locator('h1.ttl').inner_text() == 'あなたに合う本', f'{name}: ボタンでおすすめ画面へ(#recommend)')
        ok(pg.evaluate('document.activeElement.id') == 'ttl', f'{name}: 画面が変わると見出しにフォーカスが移る')
        ok(pg.locator('.rec').count() >= 3 and pg.locator('.stairs').count() == 0, f'{name}: おすすめが出る({pg.locator(".rec").count()}件)')
        ok(pg.locator('.now b').inner_text().startswith('1年まで'), f'{name}: いまの選択が見える')
        ok(noscroll(), f'{name}: 横スクロールなし(おすすめ)')
        pg.click('[data-cat="統計"]')
        cats = pg.eval_on_selector_all('.rec-meta', 'els => els.map(e => e.textContent.split("・")[0])')
        ok(len(cats) > 0 and all(c == '統計' for c in cats), f'{name}: 分野で絞れる')
        if SHOT: pg.screenshot(path=f'{SHOT}/{name}-2rec.png')
        pg.click('[data-cat="all"]')
        # 詳細 → 戻る
        pg.evaluate('window.scrollTo(0, 120)')
        pg.locator('.rec').first.click()
        ok(hs().startswith('#book-') and pg.locator('.detail').count() == 1, f'{name}: おすすめから詳細画面へ')
        ok(pg.evaluate('window.scrollY') == 0, f'{name}: 画面が変わると先頭から表示')
        ok(noscroll(), f'{name}: 横スクロールなし(詳細)')
        if SHOT: pg.screenshot(path=f'{SHOT}/{name}-4detail.png')
        pg.click('[data-act="back"]')
        ok(hs() == '#recommend' and pg.locator('.rec').count() >= 3, f'{name}: 戻るボタンでおすすめに戻る')
        pg.go_back()
        ok(hs() == '#home' or hs() == '', f'{name}: ブラウザの戻るで1つ前(授業)へ')
        pg.go_forward()
        ok(hs() == '#recommend', f'{name}: ブラウザの進むも動く')
        # 画面3: 本棚(タブ)
        pg.click('.tabs [data-go="shelf"]')
        pg.wait_for_selector('.spine')
        ok(hs() == '#shelf' and pg.locator('.spine').count() == 59, f'{name}: タブで本棚へ(59冊)')
        ok(pg.locator('.tabs [aria-current="page"]').inner_text() == '本棚', f'{name}: いまの画面がタブでわかる')
        ok(noscroll(), f'{name}: 横スクロールなし(本棚)')
        pg.click('[data-cat="統計"]')
        n = pg.locator('.spine').count()
        ok(0 < n < 59, f'{name}: 本棚も分野で絞れる({n}冊)')
        pg.click('[data-cat="all"]')
        # 本棚の位置を保ったまま詳細→戻る
        sp = pg.locator('.spine').nth(30)
        sp.scroll_into_view_if_needed()
        y0 = pg.evaluate('window.scrollY')
        sp.click()
        ok(pg.locator('.detail').count() == 1, f'{name}: 背表紙から詳細へ')
        pg.click('[data-act="back"]')
        pg.wait_for_selector('.spine')
        ok(abs(pg.evaluate('window.scrollY') - y0) < 5, f'{name}: 戻ると本棚の見ていた位置に戻る({y0})')
        if SHOT: pg.screenshot(path=f'{SHOT}/{name}-3shelf.png')
        # 足りない本には順番が出て、先に読む本へ移れる
        pg.locator('.spine.s-near, .spine.s-prep').first.click()
        ok(pg.locator('.steps li.goal').count() == 1, f'{name}: 足りない本には「おすすめの順番」が出る')
        pg.go_back()
        # 保存と、前回の続き
        pg.click('.tabs [data-go="home"]')
        pg.click('[data-stage="3"]')
        pg.goto(URL.split('#')[0]); pg.wait_for_selector('.rec')
        ok(hs() == '#recommend', f'{name}: 保存があると、次に開いたときはおすすめから始まる')
        pg.click('.now .link')
        ok(pg.locator('.step.on b').inner_text() == '3年まで', f'{name}: 選択が残っている')
        # 直接URL
        pg.goto(URL + '#shelf'); pg.wait_for_selector('.spine')
        ok(pg.locator('.spine').count() == 59, f'{name}: #shelf を直接開ける')
        pg.goto(URL + '#book-zzz'); pg.wait_for_selector('.stairs')
        ok(pg.locator('.stairs').count() == 1, f'{name}: 存在しない画面名は授業画面に戻る')
        # 消去
        pg.click('summary:has-text("しくみ")'); pg.click('[data-act="reset"]')
        ok(pg.locator('.step.on b').inner_text() == 'これから', f'{name}: 保存を消すと初期状態に戻る')
        pg.goto(URL.split('#')[0]); pg.wait_for_selector('.stairs')
        ok(pg.locator('.stairs').count() == 1, f'{name}: 消したあとは授業画面から始まる')
        ok(not errs, f'{name}: JSエラーなし {errs}')
        ctx.close()
        if SHOT:
            ctx = b.new_context(viewport={'width': w, 'height': h}, color_scheme='dark')
            pg = ctx.new_page(); pg.goto(URL); pg.wait_for_selector('.stairs'); pg.click('[data-stage="1"]'); pg.click('.go'); pg.wait_for_selector('.rec')
            pg.screenshot(path=f'{SHOT}/{name}-dark-rec.png')
            ctx.close()
    b.close()
print('\n' + (f'{len(fails)}件失敗' if fails else 'すべて成功'))
sys.exit(1 if fails else 0)
